<?php

namespace App\Contracts\Extension;

/**
 * 2단계 인증에서 메일 폴백 허용 여부를 스스로 정하는 IDV 프로바이더의 보조 계약.
 *
 * TOTP 처럼 사용자별 등록이 필요한 수단은 "아직 등록하지 않은 사용자" 를 만들어 냅니다.
 * 코어는 기본적으로 그런 사용자를 메일로 되돌려 보내 콜드스타트 락아웃을 구조적으로
 * 배제하지만, 사이트에 따라 그 우회 자체를 허용하지 않기도 합니다.
 *
 * 그 판단은 **수단을 들여온 확장**이 합니다 — 미등록자를 어떻게 다룰지 아는 유일한
 * 주체이고, 설정도 그쪽이 소유합니다. 코어에 같은 뜻의 키를 따로 두면 두 값이 어긋날 때
 * 어느 쪽이 실효인지 알 수 없게 됩니다.
 *
 * 이 계약을 구현하지 않은 프로바이더는 폴백 개념이 없는 수단(메일 자신, 외부 본인확인
 * 등)이므로 코어가 허용으로 간주합니다 — 기존 동작 불변.
 *
 * @since 7.1.0
 */
interface MailFallbackAwareProviderInterface
{
    /**
     * 이 수단을 쓸 수 없는 사용자를 메일 2단계 인증으로 되돌려 보내도 되는지 여부.
     *
     * false 면 코어는 그 사용자의 로그인을 막습니다 — 구제는 관리자 초기화 또는
     * `totp:reset` artisan 입니다.
     *
     * @return bool 메일 폴백 허용 여부
     */
    public function allowsMailFallback(): bool;
}
