<?php

namespace Plugins\Sirsoft\PayKginicis\Support;

/**
 * 결제 요청 금액 경계 상수
 *
 * PC 서명 요청은 `min:100`, 모바일 서명 요청은 `min:1` 로 같은 필드에 다른 하한이 걸려 있었습니다.
 * 모바일에서 1원 결제가 실제로 성립하고 있으므로 PG 제약이 100원이 아님이 실증되었고,
 * 100 으로 통일하면 현재 성공 중인 모바일 결제를 깨뜨립니다 → `min:1` 로 통일합니다.
 *
 * 이커머스 설정을 참조하지 않는 이유: 플러그인이 모듈 설정을 읽으면 의존성 버전 제약 상향이
 * 연쇄되므로, 이 값은 플러그인 내부 상수로 둡니다.
 */
class PaymentLimits
{
    /**
     * 결제 요청 최소 금액 (최소 화폐단위)
     */
    public const MIN_PRICE = 1;
}
