namespace Modules\Sirsoft\Ecommerce\Upgrades;

use App\Extension\AbstractUpgradeStep;

/**
 * Ecommerce 모듈 1.3.0 업그레이드 스텝
 *
 * 교환/반품/환불 통합 클레임 기능 신설에 따른 데이터 전환을 수행한다.
 * 신규 테이블·컬럼 생성은 database/migrations 가, 선언형 산출물(권한/메뉴/알림)
 * 동기화는 ModuleManager 가 담당하므로 여기서는 데이터 전환만 다룬다:
 *
 * 번호는 data/1.3.0/migrations/ 의 파일 접두 번호와 같다(파일 이름 순으로 실행된다):
 *
 *   01. 기존 환불 이력의 발생 출처를 polymorphic 축(refund_source_*)으로 백필
 *   02. 교환/반품 사유 카탈로그 시드 + 운영자·시스템 발 환불 사유 2종(`admin_cancel`·`auto_cancel_expired`) 보장
 *   03. claim 설정 카테고리 기본값 병합 (즉시취소 상태는 기존 값 승계, 실제 판정 키 `order_settings.cancellable_statuses` 도 고정)
 *   04. 배송지 스냅샷이 빈 구형 주문(1.0.0-beta.5 이전)의 배송지 백필
 *   05. 클레임 채번 시퀀스 3종(교환·반품·클레임 추가결제) 시드
 *   06. 이미 저장된 `mc_*` 다중 통화 금액의 절사 잔차 표기 정규화
 *   07. 계산 API 배송정책에 남은 후보 밖 요청 필드 정리
 *   08. 일별 판매 집계(ecommerce_stats) 기존 행 전부를 사이트 하루·새 순매출 식으로 재집계
 *   09. 같은 상품옵션 활성 행 금액이 겹친 주문 보고 (값 불변)
 *   10. 부분취소 주문의 헤더 적립 예정액을 남은 상품 행의 합으로 보정 (겹침 주문은 경고만)
 *   11. 상품이 전부 반품완료(일부 취소)인 주문의 주문 상태를 반품완료로 보정
 *   12. 저장된 레이아웃의 예전 임시 키 생성식을 `$uuid()` 로 보정 (빈 map `{}` 보존)
 *   13. 이미지 저장 폴더로 쓸 수 없는 기존 상품 코드 보고 (값 불변)
 *   14. 1.2.1 시절 운영자가 만든 택배사·배송유형·클레임 사유에 생성자 표식 (재시드 정리에서 보호)
 *   15. 신설한 「주문 삭제」 권한(`orders.delete`)이 admin 역할에 붙었는지 확인 — 선언형 동기화의 안전망.
 *       정의가 없던 이 권한을 관리자 주문 삭제와 개인정보 보유기간 「삭제」 방식 직권 실행이 요구해 아무도 실행할 수 없었다.
 *
 * 12·13 은 예전에 01·02 와 번호가 겹쳐 있었다 — 서로 순서 의존이 없어 끝 번호로 옮겼다(7.1.0 출시 점검 EU-10).
 *
 * 08 번이 필요한 이유 — 1.2.1 의 대시보드 집계식은 unit_price × (quantity − cancelled_quantity) 였다.
 * 부분취소는 분할로 남은 행의 quantity 를 이미 줄이고 같은 행 cancelled_quantity 에도 취소 수량을 더하므로
 * 취소 수량이 두 번 빠졌다. 또 날짜는 UTC 하루로 묶였는데 1.3.0 런타임은 사이트 표준시 하루로 센다. 스케줄러는
 * 최근 7일만 다시 쓰므로 그 이전 행 전부를 사이트 하루·새 식으로 다시 쓴다(판매 수량·순매출·상태 배지).
 *
 * 09 번이 필요한 이유 — 1.2.1 의 부분취소 재계산은 결과를 상품옵션 키로 맞춰 써서, 같은 상품옵션이 상태가
 * 다른 두 행으로 나뉜 주문에서는 두 행이 각각 합계 금액·적립 예정액을 받았다. 주문 금액은 거래 시점으로
 * 동결하는 원칙(06 번과 같음)이고 행 금액을 다시 나누려면 계산 엔진이 필요해 값은 바꾸지 않고, 구매확정 전
 * 적립을 확인하도록 주문번호를 남긴다.
 *
 * 10 번이 필요한 이유 — 1.2.1 의 부분취소 재계산은 행별 적립 예정액만 다시 쓰고 주문 헤더(`total_earned_points_amount`)는
 * 취소 전 값으로 두었다. 1.3.0 은 재계산 때 헤더도 맞추지만 이미 틀린 주문은 남는다. 헤더는 표시값(적립 원장은 행 단위)이라
 * 남은 행의 합으로 바꿔도 지급액은 그대로다 — 행 금액을 다시 나누는 09 번과 달리 계산 엔진이 필요 없다.
 *
 * 11 번이 필요한 이유 — 출시본 1.2.1 에는 반품 기능이 없어 대상이 없다. 1.3.0 개발 중 빌드로 먼저 설치한 사이트에서는
 * 반품 완료가 행 상태만 바꿔 전량 반품 주문이 「배송완료」로 남고 개인정보 보존기간 파기의 종결 대상에서 빠졌다. 1.3.0 은
 * 완료 때 주문을 반품완료로 바꾸고, 그렇게 남은 주문은 여기서 맞춘다(대상이 없으면 아무것도 하지 않는다). 개발 빌드
 * 사이트는 모듈 버전이 이미 1.3.0 이라 이 스텝들이 자동으로 돌지 않는다 — `php artisan module:update sirsoft-ecommerce --force`
 * 로 다시 돌린다(모든 스텝이 멱등이고 08 번도 런타임과 같은 축이라 재실행이 값을 틀리게 만들지 않는다).
 *
 * 06 번이 필요한 이유 — 1.3.0 은 절사 결과를 만드는 지점에서 되곱하기 잔차를 지우지만 그것은
 * 이후 기록분에만 적용된다. 출시본에 이미 있던 주문·주문옵션·결제·배송·환불 테이블의 과거
 * 행은 `45.050000000000004` 같은 표기를 그대로 들고 있고, 그 값이 연동 시스템이 내려받는
 * 원본 금액으로 계속 나간다. 클레임 테이블은 1.3.0 신설이라 대상 행이 없다.
 *
 * 05 번이 여기 있는 이유 — 시퀀스는 위 문단이 말한 "선언형 산출물" 이 아니다. 권한/메뉴/알림은
 * ModuleManager::syncDeclarativeArtifacts() 가 업데이트마다 다시 맞춰 주지만, 시퀀스는
 * SequenceSeeder 가 만들고 그 시더는 ModuleManager::runModuleSeeders() 안에 있으며 그
 * 메서드는 installModule() 에서만 불린다. 그래서 1.3.0 이 새로 도입한 시퀀스 타입은
 * 신규 설치본에만 생기고 기존 설치본은 업그레이드해도 행이 없는 채로 남는다.
 *
 * 12 번 — 상품·분류 이미지와 상품 문의의 임시 키가 UUID 만 받게 되면서(1.3.0), 레이아웃 편집기로 고쳐 둔 화면이나
 * 「편집본 유지」 업데이트 화면에 남은 예전 임시 키 생성식을 `$uuid()` 로 바꾼다.
 *
 * 14 번이 필요한 이유 — 1.3.0 시더는 시드 목록에서 빠진 미사용 행을 정리하되 운영자가 만든 행은 남기려고 범위를
 * `created_by IS NULL` 로 좁혔는데, 1.2.1 관리자 화면은 created_by 를 채우지 않았다. 역대 시더 코드 밖의 그런 행에
 * 최고관리자를 생성자로 채워 언어팩 활성화·재시드 때 지워지지 않게 한다.
 *
 * 모든 비즈니스 로직은 data/1.3.0/migrations/ 로 격리(AbstractUpgradeStep 규약).
 *
 * 백필하지 않는 것 — `ecommerce_orders.total_refunded_amount` / `total_refunded_points_amount`
 *
 * 1.3.0 부터 RefundExecutionService::execute() 가 이 두 컬럼을 누적한다(클레임 환불 경로).
 * 기존 주문은 값이 전부 0 이지만 과거 환불액으로 채우지 않는다 — 1.3.0 이전의 환불은 전부
 * 취소 경로에서 발생했고, 취소는 `total_paid_amount` 자체를 재계산값으로 덮어써 이미 반영돼
 * 있기 때문이다. 여기에 과거 환불액을 더하면 OrderAdjustmentService 의 잔여 결제 한도
 * (`total_paid_amount - total_refunded_amount`)가 같은 금액을 두 번 빼게 되어, 아직 환불
 * 가능한 기존 주문의 환불 한도가 실제보다 낮게 잠긴다. 오류 없이 금액만 줄어드는 형태라
 * 발견도 어렵다.
 *
 * @upgrade-path A
 */
